package fsm.sample.export

/**
 * PURPOSE: Render [TransitionTable] as a Markdown table (stdlib string builder).
 * No diagram libraries — plain GFM markdown for docs and demo output.
 */
fun formatMarkdownTable(table: TransitionTable): String {
    val sb = StringBuilder()
    sb.appendLine("### ${table.machine} transition table")
    sb.appendLine()
    sb.appendLine("| From | Event | To | Kind | Note |")
    sb.appendLine("| --- | --- | --- | --- | --- |")
    for (row in table.rows) {
        val note = row.note ?: ""
        sb.appendLine(
            "| ${row.from} | ${row.event} | ${row.to} | ${row.kind.name} | $note |",
        )
    }
    return sb.toString().trimEnd()
}

/**
 * PURPOSE: Bundle several machine tables into one Markdown document section.
 */
fun formatMarkdownDocument(tables: List<TransitionTable>, title: String = "State transition tables"): String {
    val sb = StringBuilder()
    sb.appendLine("# $title")
    sb.appendLine()
    sb.appendLine("Generated by product evaluation of shipped pure `State + Event → State` APIs.")
    sb.appendLine("No FSM/statechart library. Rows: every finite (state, event) pair.")
    sb.appendLine()
    for (t in tables) {
        sb.appendLine(formatMarkdownTable(t))
        sb.appendLine()
    }
    return sb.toString().trimEnd() + "\n"
}
